import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** Copies the compiled HyperdriveDesk ABI into the backend and frontend as typed `as const` modules. */
const here = path.dirname(fileURLToPath(import.meta.url));
const artifact = JSON.parse(
  readFileSync(
    path.join(here, "../artifacts/contracts/HyperdriveDesk.sol/HyperdriveDesk.json"),
    "utf8",
  ),
) as { abi: unknown[] };

const body = `// Generated by contracts/scripts/export-abi.ts. Do not edit by hand.\nexport const hyperdriveDeskAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;

const read = (p: string) => JSON.parse(readFileSync(path.join(here, "../artifacts/contracts", p), "utf8")).abi;
const basketBody = `// Generated by contracts/scripts/export-abi.ts. Do not edit by hand.
export const hyperdriveBasketAbi = ${JSON.stringify(read("basket/HyperdriveBasket.sol/HyperdriveBasket.json"), null, 2)} as const;
export const basketRouterAbi = ${JSON.stringify(read("basket/BasketRouter.sol/BasketRouter.json"), null, 2)} as const;
`;
for (const target of ["../../backend/src/chain/basket-abi.ts", "../../frontend/lib/basket-abi.ts"]) {
  writeFileSync(path.join(here, target), basketBody);
  console.log(`wrote ${target}`);
}

for (const target of ["../../backend/src/chain/desk-abi.ts", "../../frontend/lib/desk-abi.ts"]) {
  const out = path.join(here, target);
  writeFileSync(out, body);
  console.log(`wrote ${path.relative(path.join(here, "../.."), out)}`);
}
